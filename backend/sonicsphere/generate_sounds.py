def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="regenerate existing files")
    ap.add_argument("--voice-file", type=Path, default=None,
                    help="your own recording of “Come here” (WAV/FLAC/OGG/MP3); replaces the TTS voice and "
                         "marks it publishable")
    args = ap.parse_args(argv)
    out_dir = get_settings().sounds_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    prev_path = out_dir / "manifest.json"
    previous = {m["id"]: m for m in json.loads(prev_path.read_text(encoding="utf-8"))} if prev_path.is_file() else {}
    manifest = []
    with tempfile.TemporaryDirectory() as td:
        for s in SOUNDS:
            path = out_dir / s["file"]
            meta = {k: v for k, v in s.items() if k != "fn"}
            if s["id"] == "come_here" and args.voice_file is not None:
                x, fs = sf.read(args.voice_file, dtype="float64")
                x = process_voice(x, fs, presence=0.6, highpass=90.0)
                sf.write(path, x, FS, subtype="PCM_16")
                meta.update({"source": f"Recorded by the site owner ({args.voice_file.name}).",
                             "license": "Own recording, published by the site owner", "publishable": True})
                print(f"  [ok] {s['file']} from your recording ({x.size / FS:.2f} s)")
            elif args.force or not path.is_file():
                if s["fn"] is not None:
                    x = s["fn"]()
                else:
                    res = voice(Path(td))
                    if res is None:
                        print(f"  [skip] {s['file']}: no Windows TTS available. Record \"Come here\" yourself and save "
                              f"it as {path} (mono WAV), then rerun.")
                        continue
                    x, used = res
                    meta["source"] += f" Voice: {used}."
                sf.write(path, x, FS, subtype="PCM_16")
                print(f"  [ok] {s['file']} ({x.size / FS:.2f} s)")
            elif s["id"] in previous:
                # File kept as is: keep its recorded provenance (e.g. which voice, or your own recording).
                # Synthesised sounds always take the current definition (they are reproducible).
                if s["fn"] is None:
                    for k in ("source", "license", "publishable"):
                        if k in previous[s["id"]]:
                            meta[k] = previous[s["id"]][k]
            info = sf.info(path)
            meta.update({"duration_s": round(info.frames / info.samplerate, 3), "sample_rate": info.samplerate,
                         "channels": info.channels})
            manifest.append(meta)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {out_dir / 'manifest.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
