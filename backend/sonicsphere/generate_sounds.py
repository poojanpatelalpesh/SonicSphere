"""Generate the four built-in sounds into ``assets/sounds`` with a licensing manifest.

* helicopter.wav - original procedural synthesis (rotor blade slap, tail rotor, turbine)
* ak47.wav       - original procedural synthesis of automatic rifle fire at the AK-47's
                   ~600 rounds/min cyclic rate (muzzle blast, mechanism, reflections)
* guitar.wav     - original Karplus-Strong plucked-string synthesis (Am-F-C-G arpeggios)
* come_here.wav  - the phrase "Come here!" rendered locally with the Windows speech
                   synthesizer (scripts/generate_voice.ps1), then trimmed/normalised

The synthesized sounds are original works generated by this script (CC0 1.0). The voice
clip is produced by the user's own operating-system TTS engine; see the manifest.

Run:  python -m sonicsphere.generate_sounds [--force]
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import butter, lfilter, sosfilt

from .config import get_settings

FS = 44100
REPO = Path(__file__).resolve().parents[2]


def _bp(lo, hi, order=2):
    return butter(order, [lo / (FS / 2), hi / (FS / 2)], btype="band", output="sos")


def _lp(fc, order=2):
    return butter(order, fc / (FS / 2), output="sos")


def _hp(fc, order=2):
    return butter(order, fc / (FS / 2), btype="high", output="sos")


def _fade(x, ms=10):
    n = int(FS * ms / 1000)
    w = np.ones_like(x)
    w[:n] = np.linspace(0, 1, n)
    w[-n:] = np.linspace(1, 0, n)
    return x * w


def _peak(x, db=-1.0):
    return x / np.max(np.abs(x)) * 10 ** (db / 20)


def _loopable(x, xfade_s=0.25):
    """Make a sustained sound loop seamlessly: crossfade its tail into its head."""
    n = int(xfade_s * FS)
    head, body, tail = x[:n], x[n:-n] if n else x, x[-n:]
    w = np.sqrt(np.linspace(0, 1, n))
    return np.concatenate([tail * w[::-1] + head * w, body])


def helicopter(seconds=8.0, rng=None):
    rng = rng or np.random.default_rng(11)
    n = int(seconds * FS)
    t = np.arange(n) / FS
    bpf = 11.0                         # main rotor blade-passage frequency (2 blades, 330 rpm)
    out = np.zeros(n)
    # Blade slap: an impulsive, band-limited noise burst plus a low thump at every blade passage.
    slap_len = int(0.06 * FS)
    env = np.exp(-np.arange(slap_len) / (0.012 * FS))
    thump = np.sin(2 * np.pi * 55 * np.arange(slap_len) / FS) * np.exp(-np.arange(slap_len) / (0.02 * FS))
    noise_burst_sos = _bp(400, 7000)
    for k in range(int(seconds * bpf)):
        i = int(k / bpf * FS + rng.normal(0, 0.0008) * FS)
        if i < 0 or i + slap_len > n:
            continue
        burst = sosfilt(noise_burst_sos, rng.standard_normal(slap_len)) * env
        a = 0.85 + 0.15 * rng.random()
        out[i:i + slap_len] += a * (1.6 * burst + 0.35 * thump)
    # Tail rotor: faster buzz (~57 Hz) with harmonics, amplitude modulated.
    tr = sum(np.sin(2 * np.pi * 57 * h * t + rng.random() * 6.28) / h for h in range(1, 7))
    tr *= 0.08 * (1 + 0.3 * np.sin(2 * np.pi * 9.5 * t))
    # Turbine whine with slow drift.
    drift = 1 + 0.004 * np.sin(2 * np.pi * 0.25 * t)
    whine = 0.035 * np.sin(2 * np.pi * np.cumsum(3150 * drift) / FS) + 0.025 * np.sin(2 * np.pi * np.cumsum(5400 * drift) / FS)
    # Broadband rotor wash / engine rumble.
    rumble = sosfilt(_lp(250, 4), rng.standard_normal(n)) * 0.08
    wash = sosfilt(_bp(800, 12000), rng.standard_normal(n)) * 0.16 * (1 + 0.6 * np.sin(2 * np.pi * bpf * t))
    x = out + tr + whine + rumble + wash
    x = sosfilt(_hp(30), x)
    return _peak(_loopable(np.tanh(1.3 * x / np.max(np.abs(x))) ), -1.0)


def ak47(seconds=4.0, rng=None):
    rng = rng or np.random.default_rng(47)
    n = int(seconds * FS)
    out = np.zeros(n)
    period = 60.0 / 600.0             # cyclic rate ~600 rounds per minute
    shot_times = []
    for start, count in ((0.10, 6), (1.25, 4), (2.20, 9)):
        shot_times += [start + k * period + rng.normal(0, 0.003) for k in range(count)]
    L = int(0.45 * FS)
    tt = np.arange(L) / FS
    for st in shot_times:
        i = int(st * FS)
        blast = rng.standard_normal(L) * np.exp(-tt / 0.004)
        blast = sosfilt(_bp(120, 9000), blast) * 3.0
        boom = np.sin(2 * np.pi * (95 + 30 * np.exp(-tt / 0.01)) * tt) * np.exp(-tt / 0.03) * 0.7
        crack = sosfilt(_hp(2500), rng.standard_normal(L)) * np.exp(-tt / 0.0015) * 1.8
        mech_d = int(0.012 * FS)
        mech = np.zeros(L)
        m = sosfilt(_bp(1800, 5000), rng.standard_normal(L - mech_d)) * np.exp(-tt[: L - mech_d] / 0.003) * 0.35
        mech[mech_d:] = m
        refl = sosfilt(_lp(1800), rng.standard_normal(L)) * np.exp(-tt / 0.12) * 0.25 * (tt > 0.02)
        shot = (blast + boom + crack + mech + refl) * (0.9 + 0.2 * rng.random())
        end = min(n, i + L)
        out[i:end] += shot[: end - i]
    out = np.tanh(1.6 * out / np.max(np.abs(out)))
    return _peak(_fade(out, 5), -1.0)


def _pluck(f0, dur, rng, brightness=0.6, decay=0.996):
    n = int(dur * FS)
    period = FS / f0
    N = int(np.floor(period - 0.5))
    frac = period - 0.5 - N
    exc = rng.standard_normal(N + 2)
    exc = lfilter([brightness, 1 - brightness], [1.0], exc)      # pluck brightness
    pos = max(1, int(0.18 * N))                                    # pluck-position comb
    exc[pos:] -= 0.5 * exc[:-pos]
    x = np.zeros(n)
    x[: exc.size] = exc
    a = np.zeros(N + 3)
    a[0] = 1.0
    # Loop: two-point average (low-pass, delay 0.5) and linear-interpolated fractional delay.
    a[N] = -decay * 0.5 * (1 - frac)
    a[N + 1] = -decay * 0.5
    a[N + 2] = -decay * 0.5 * frac
    y = lfilter([1.0], a, x)
    return y * np.exp(-np.arange(n) / (FS * dur * 0.6))


def guitar(seconds=8.0, rng=None):
    rng = rng or np.random.default_rng(5)
    n = int(seconds * FS)
    out = np.zeros(n + FS * 3)
    midi = lambda m: 440.0 * 2 ** ((m - 69) / 12)
    chords = {  # MIDI notes from low to high string
        "Am": [45, 52, 57, 60, 64],
        "F": [41, 48, 53, 57, 60, 65],
        "C": [48, 52, 55, 60, 64],
        "G": [43, 47, 50, 55, 59, 67],
    }
    beat = 0.25
    t0 = 0.05
    for bar, name in enumerate(["Am", "F", "C", "G"]):
        notes = chords[name]
        pattern = [0, 2, 3, 4, 3, 2, 1, 3]   # arpeggio order (indices into the chord)
        for k, idx in enumerate(pattern):
            m = notes[min(idx, len(notes) - 1)]
            st = t0 + bar * 2.0 + k * beat + rng.normal(0, 0.004)
            y = _pluck(midi(m), 2.6, rng, brightness=0.55 + 0.1 * rng.random()) * (0.8 + 0.2 * rng.random())
            i = int(st * FS)
            out[i:i + y.size] += y
    # Simple body: a few resonances.
    body = sum(sosfilt(_bp(f * 0.9, f * 1.1, 1), out) * g for f, g in ((105, 0.5), (210, 0.35), (420, 0.2)))
    x = out + body
    x = sosfilt(_hp(60), x)[:n]
    return _peak(_fade(x, 30), -1.0)


def voice(tmpdir: Path) -> tuple[np.ndarray, str] | None:
    ps1 = REPO / "scripts" / "generate_voice.ps1"
    exe = shutil.which("powershell") or shutil.which("pwsh")
    if platform.system() != "Windows" or exe is None or not ps1.is_file():
        return None
    raw = tmpdir / "voice_raw.wav"
    res = subprocess.run([exe, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(ps1), "-OutFile", str(raw)],
                         capture_output=True, text=True, timeout=120)
    if res.returncode != 0 or not raw.is_file():
        print(res.stdout, res.stderr)
        return None
    used = next((ln.split("=", 1)[1] for ln in res.stdout.splitlines() if ln.startswith("voice=")), "unknown")
    x, fs = sf.read(raw, dtype="float64")
    return process_voice(x, fs, presence=2.2, highpass=170.0), used


def process_voice(x: np.ndarray, fs: float, presence: float, highpass: float) -> np.ndarray:
    """Mono, 44.1 kHz, trimmed, high-passed, with a presence shelf (ILD cues live above ~2 kHz)."""
    if x.ndim > 1:
        x = x.mean(axis=1)
    if fs != FS:
        from .audio_processing import resample
        x = resample(x, fs, FS)
    # Trim silence (-45 dB) and keep 60 ms of margin.
    thr = np.max(np.abs(x)) * 10 ** (-45 / 20)
    idx = np.nonzero(np.abs(x) > thr)[0]
    a, b = max(0, idx[0] - int(0.06 * FS)), min(x.size, idx[-1] + int(0.06 * FS))
    x = sosfilt(_hp(highpass, 2), x[a:b])
    # Presence lift: TTS voices carry little energy above 2 kHz, where interaural level
    # differences are largest; a shelf from ~2.5 kHz (+9 dB for TTS) makes the voice localise clearly.
    x = x + presence * sosfilt(_hp(2500, 2), x)
    pad = np.zeros(int(0.35 * FS))
    return _peak(np.concatenate([np.zeros(int(0.05 * FS)), _fade(x, 8), pad]), -1.0)


